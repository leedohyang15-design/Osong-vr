// Builds js/figures-data.js and assets/figures/*.webp from Stellarium's "western" sky culture
// (illustrations by Johan Meuris, Free Art License).
// usage: node tools/build-figures.js <path to d3-celestial package dir>
// needs network access to raw.githubusercontent.com
const fs = require('fs'), path = require('path'), https = require('https');
const ROOT = path.join(__dirname, '..');
const BASE = 'https://raw.githubusercontent.com/Stellarium/stellarium-skycultures/master/western/';
const D3C = process.argv[2];
if (!D3C) { console.error('usage: node tools/build-figures.js <d3-celestial dir>'); process.exit(1); }

function get(url) {
  return new Promise((res, rej) => https.get(url, r => {
    if (r.statusCode !== 200) return rej(new Error(r.statusCode + ' ' + url));
    const b = []; r.on('data', c => b.push(c)); r.on('end', () => res(Buffer.concat(b)));
  }).on('error', rej));
}
(async () => {
  const hip = {};
  for (const f of ['stars.14.json', 'stars.8.json', 'stars.6.json']) {
    const p = path.join(D3C, 'data', f);
    if (!fs.existsSync(p)) continue;
    for (const s of JSON.parse(fs.readFileSync(p)).features) {
      let [ra, dec] = s.geometry.coordinates; if (ra < 0) ra += 360;
      hip[s.id] = [+ra.toFixed(4), +dec.toFixed(4)];
    }
  }
  const idx = JSON.parse(await get(BASE + 'index.json'));
  const out = {}, dir = path.join(ROOT, 'assets', 'figures');
  fs.mkdirSync(dir, { recursive: true });
  let missing = 0;
  for (const c of idx.constellations) {
    if (!c.image) continue;
    const id = c.iau || c.id.split(' ').pop();
    const anchors = c.image.anchors.map(a => {
      const p = hip[a.hip]; if (!p) { missing++; console.warn('no HIP', a.hip, id); return null; }
      return [a.pos[0], a.pos[1], p[0], p[1]];
    });
    if (anchors.some(a => !a)) continue;
    const file = path.basename(c.image.file);
    fs.writeFileSync(path.join(dir, file), await get(BASE + c.image.file));
    out[id] = { file: 'assets/figures/' + file, size: c.image.size, anchors };
  }
  fs.writeFileSync(path.join(ROOT, 'js', 'figures-data.js'),
    '// Constellation illustrations by Johan Meuris (Stellarium, Free Art License). Generated by tools/build-figures.js.\n' +
    '// anchors: [imageX, imageY, ra, dec] for three stars\nvar FIGURE_ART = ' + JSON.stringify(out) + ';\n');
  console.log('figures', Object.keys(out).length, 'missing anchors', missing);
})().catch(e => { console.error(e); process.exit(1); });
