  function toVec(ra0, dec0, x, y) {
    var xi = -x * D2R, eta = y * D2R, d0 = dec0 * D2R;
    var rho = Math.hypot(xi, eta);
    var ra, dec;
    if (rho < 1e-9) { ra = ra0 * D2R; dec = d0; }
    else {
      var c = Math.atan(rho), sc = Math.sin(c), cc = Math.cos(c);
      dec = Math.asin(cc * Math.sin(d0) + eta * sc * Math.cos(d0) / rho);
      ra = ra0 * D2R + Math.atan2(xi * sc, rho * Math.cos(d0) * cc - eta * Math.sin(d0) * sc);
    }
    var cd = Math.cos(dec);
    return [cd * Math.cos(ra), cd * Math.sin(ra), Math.sin(dec)];
  }
  function smooth(pts, closed) {
    var n = pts.length, out = [];
    if (n < 3) return pts.slice();
    var SUB = 4;
    function P(i) { return closed ? pts[(i + n) % n] : pts[Math.max(0, Math.min(n - 1, i))]; }
    var last = closed ? n : n - 1;
    for (var i = 0; i < last; i++) {
      var p0 = P(i - 1), p1 = P(i), p2 = P(i + 1), p3 = P(i + 2);
      for (var s = 0; s < SUB; s++) {
        var t = s / SUB, t2 = t * t, t3 = t2 * t;
        out.push([
          0.5 * (2 * p1[0] + (-p0[0] + p2[0]) * t + (2 * p0[0] - 5 * p1[0] + 4 * p2[0] - p3[0]) * t2 + (-p0[0] + 3 * p1[0] - 3 * p2[0] + p3[0]) * t3),
          0.5 * (2 * p1[1] + (-p0[1] + p2[1]) * t + (2 * p0[1] - 5 * p1[1] + 4 * p2[1] - p3[1]) * t2 + (-p0[1] + 3 * p1[1] - 3 * p2[1] + p3[1]) * t3)
        ]);
      }
    }
    out.push(closed ? pts[0] : pts[n - 1]);
    return out;
  }
  // body frame -> chart frame: origin (ox, oy), body "up" along (ux, uy), body "forward" 90 degrees clockwise from up
  function place(xf, q) {
    var l = Math.hypot(xf[2], xf[3]), ux = xf[2] / l, uy = xf[3] / l;
    return [xf[0] + q[0] * uy + q[1] * ux, xf[1] - q[0] * ux + q[1] * uy];
  }
  function parse(str) {
    var closed = /z\s*$/.test(str);
    var pts = str.replace(/z\s*$/, '').trim().split(/\s+/).map(function (p) { var a = p.split(','); return [+a[0], +a[1]]; });
    return { pts: pts, closed: closed };
  }
  var OUT = {};
  Object.keys(RAW).forEach(function (id) {
    var f = RAW[id], ra0 = f[0], dec0 = f[1], xf = f[3];
    var paths = f[2].map(function (s) {
      var p = parse(s);
      return smooth(xf ? p.pts.map(function (q) { return place(xf, q); }) : p.pts, p.closed)
        .map(function (q) { return toVec(ra0, dec0, q[0], q[1]); });
    });
    // arc length per path (radians) so the pen-drawing animation runs at an even speed
    var lens = paths.map(function (pts) {
      var L = 0;
      for (var i = 1; i < pts.length; i++) {
        var a = pts[i - 1], b = pts[i];
        L += Math.hypot(a[0] - b[0], a[1] - b[1], a[2] - b[2]);
      }
      return L;
    });
    OUT[id] = { paths: paths, lens: lens, total: lens.reduce(function (a, b) { return a + b; }, 0) };
  });
  OUT._raw = RAW; OUT._parse = parse; OUT._smooth = smooth; OUT._place = place;
  return OUT;
